I3D Mapping Exporter - XML Updater
Purpose:
  Updates the i3dMappings section in an existing vehicle/placeable XML.

How it works:
  - The GE Lua script copies generated mappings to the Windows clipboard.
  - The BAT file starts this script and passes the target XML using -TargetXml and the UI language using -Language.
  - Existing mapping IDs get their node path updated; missing IDs are added.
  - Mapping entries are normalized to node="0>..." />. Other mapping IDs remain.

Formatting and file handling:
  - Edits the XML text directly instead of serializing the whole document.
  - Keeps unrelated text, blank lines, indentation, line endings, and file encoding.
  - Writes through a temporary file before replacing the target XML.

Requirements:
  - Windows PowerShell with Get-Clipboard and Windows Forms available.
  - Clipboard text must contain mapping elements generated by the GE Lua script.
  - The target XML must already contain an i3dMappings section.

The script displays a message box with the update result or any error.

